"use client";

import { useEffect, useMemo, useState } from "react";
import { api } from "@/lib/api-client";
import type { SwimmingStyleDTO, TrainingPlanDTO, TrainingPlanStatus } from "@/lib/types";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Badge } from "@/components/ui/badge";
import { ClipboardList, Plus, Save, Trash2, ArrowUp, ArrowDown, PlayCircle, Copy, Pencil } from "lucide-react";
import { toast } from "sonner";
import { generateTrainingPlanName } from "@/lib/training-plan";

type DraftSet = {
  key: string; distanceMeters: number; repeatCount: number; swimmingStyleId: string;
  targetTimeSeconds: string; restIntervalSeconds: string; notes: string;
};

const newSet = (): DraftSet => ({
  key: crypto.randomUUID(), distanceMeters: 50, repeatCount: 4, swimmingStyleId: "",
  targetTimeSeconds: "", restIntervalSeconds: "", notes: "",
});

export function TrainingPlanView() {
  const [styles, setStyles] = useState<SwimmingStyleDTO[]>([]);
  const [plans, setPlans] = useState<TrainingPlanDTO[]>([]);
  const [planDate, setPlanDate] = useState(new Date().toISOString().slice(0, 10));
  const [planName, setPlanName] = useState("");
  const [period, setPeriod] = useState("");
  const [isPlanNameAutoGenerated, setIsPlanNameAutoGenerated] = useState(true);
  const [planNameManuallyEdited, setPlanNameManuallyEdited] = useState(false);
  const [remarks, setRemarks] = useState("");
  const [status, setStatus] = useState<TrainingPlanStatus>("DRAFT");
  const [sets, setSets] = useState<DraftSet[]>([newSet()]);
  const [saving, setSaving] = useState(false);
  const [editingPlanId, setEditingPlanId] = useState<string | null>(null);
  const [copyMode, setCopyMode] = useState<"PREVIOUS_DAY" | "SAME_DAY_LAST_WEEK" | "DATE" | "SOURCE">("PREVIOUS_DAY");
  const [copySourceDate, setCopySourceDate] = useState("");
  const [copySourcePlanId, setCopySourcePlanId] = useState("");
  const [copying, setCopying] = useState(false);

  const generatedPlanName = useMemo(() => generateTrainingPlanName(
    planDate,
    sets.map((set) => styles.find((style) => style.id === set.swimmingStyleId)?.styleName ?? ""),
    period
  ), [planDate, sets, styles, period]);

  useEffect(() => {
    if (!generatedPlanName || planNameManuallyEdited) return;
    const timer = window.setTimeout(() => {
      setPlanName(generatedPlanName);
      setIsPlanNameAutoGenerated(true);
    }, 0);
    return () => window.clearTimeout(timer);
  }, [generatedPlanName, planNameManuallyEdited]);

  const load = async () => {
    const [styleRows, planRows] = await Promise.all([
      api.get<SwimmingStyleDTO[]>("/api/styles"), api.get<TrainingPlanDTO[]>("/api/training-plans"),
    ]);
    setStyles(styleRows.filter((style) => style.isActive));
    setPlans(planRows);
    setSets((current) => current.map((set) => set.swimmingStyleId ? set : { ...set, swimmingStyleId: styleRows.find((style) => style.isActive)?.id ?? "" }));
  };

  useEffect(() => {
    const timer = window.setTimeout(() => load().catch((error) => toast.error(error.message)), 0);
    return () => window.clearTimeout(timer);
  }, []);

  const updateSet = (key: string, patch: Partial<DraftSet>) => setSets((rows) => rows.map((row) => row.key === key ? { ...row, ...patch } : row));
  const move = (index: number, offset: number) => setSets((rows) => {
    const next = [...rows]; const target = index + offset;
    if (target < 0 || target >= next.length) return rows;
    [next[index], next[target]] = [next[target], next[index]]; return next;
  });

  const resetForm = () => {
    setEditingPlanId(null); setPlanName(""); setRemarks(""); setStatus("DRAFT"); setPeriod("");
    setPlanNameManuallyEdited(false); setIsPlanNameAutoGenerated(true);
    setSets([{ ...newSet(), swimmingStyleId: styles[0]?.id ?? "" }]);
  };

  const openForEdit = (plan: TrainingPlanDTO) => {
    setEditingPlanId(plan.id); setPlanDate(plan.planDate.slice(0, 10)); setPlanName(plan.planName);
    setRemarks(plan.remarks ?? ""); setStatus(plan.status); setPeriod("");
    setIsPlanNameAutoGenerated(false); setPlanNameManuallyEdited(true);
    setSets(plan.sets.map((set) => ({ key: crypto.randomUUID(), distanceMeters: set.distanceMeters,
      repeatCount: set.repeatCount, swimmingStyleId: set.swimmingStyleId,
      targetTimeSeconds: set.targetTimeSeconds?.toString() ?? "",
      restIntervalSeconds: set.restIntervalSeconds?.toString() ?? "", notes: set.notes ?? "" })));
    window.scrollTo({ top: 0, behavior: "smooth" });
    if ((plan.completedRunCount ?? 0) > 0 || (plan._count?.runs ?? 0) > 0) toast.warning("This plan has practice history. Historical run snapshots will remain unchanged.");
  };

  const save = async () => {
    if (!planName.trim()) return toast.error("Enter a plan name");
    if (sets.some((set) => !set.swimmingStyleId)) return toast.error("Select a style for every set");
    setSaving(true);
    try {
      const payload = {
        planDate: new Date(`${planDate}T12:00:00Z`).toISOString(), planName, period, remarks, status,
        sets: sets.map((set, index) => ({
          sequenceNo: index + 1, distanceMeters: Number(set.distanceMeters), repeatCount: Number(set.repeatCount),
          swimmingStyleId: set.swimmingStyleId,
          targetTimeSeconds: set.targetTimeSeconds === "" ? null : Number(set.targetTimeSeconds),
          restIntervalSeconds: set.restIntervalSeconds === "" ? null : Number(set.restIntervalSeconds), notes: set.notes,
        })),
      };
      if (editingPlanId) await api.patch(`/api/training-plans/${editingPlanId}`, payload);
      else await api.post("/api/training-plans", payload);
      toast.success(editingPlanId ? "Training plan updated" : status === "ACTIVE" ? "Active training plan created" : "Training plan saved");
      resetForm();
      await load();
    } catch (error: any) { toast.error(error.message); } finally { setSaving(false); }
  };

  const sourceDateForMode = copyMode === "PREVIOUS_DAY"
    ? new Date(new Date(`${planDate}T12:00:00Z`).getTime() - 86400000).toISOString().slice(0, 10)
    : copyMode === "SAME_DAY_LAST_WEEK"
    ? new Date(new Date(`${planDate}T12:00:00Z`).getTime() - 7 * 86400000).toISOString().slice(0, 10)
    : copySourceDate;
  const copySource = copyMode === "SOURCE"
    ? plans.find((plan) => plan.id === copySourcePlanId)
    : plans.find((plan) => plan.planDate.slice(0, 10) === sourceDateForMode);
  const copyPreviewName = copySource
    ? generateTrainingPlanName(planDate, copySource.sets.map((set) => set.style.styleName), period)
    : "";

  const copyPlan = async () => {
    if (!copySource) return toast.error("No matching source plan was found");
    if (!window.confirm(`Copy ${copySource.planName} (${copySource.sets.length} sets) to ${planDate} as ${copyPreviewName}?`)) return;
    setCopying(true);
    try {
      const copied = await api.post<TrainingPlanDTO>("/api/training-plans/copy", {
        sourcePlanId: copySource.id, mode: copyMode, sourceDate: copySourceDate,
        newPlanDate: planDate, period,
      });
      await load(); openForEdit(copied); toast.success("Plan copied as a new Draft and opened for editing");
    } catch (error: any) { toast.error(error.message); } finally { setCopying(false); }
  };

  const activate = async (id: string) => {
    try { await api.patch(`/api/training-plans/${id}`, { status: "ACTIVE" }); await load(); toast.success("Plan is active and ready in Practice Console"); }
    catch (error: any) { toast.error(error.message); }
  };

  return <div className="space-y-4 max-w-6xl mx-auto">
    <div className="flex items-center gap-2"><ClipboardList className="size-6 text-aqua" /><div><h1 className="text-xl sm:text-2xl font-bold">Training Plan</h1><p className="text-sm text-muted-foreground">Build today&apos;s practice sets before timing starts.</p></div></div>
    <Card className="border-aqua/25">
      <CardHeader><CardTitle className="text-base flex items-center gap-2"><Copy className="size-4 text-aqua" /> Copy Existing Plan</CardTitle></CardHeader>
      <CardContent className="space-y-3">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-2">
          <Button variant={copyMode === "PREVIOUS_DAY" ? "default" : "outline"} className="h-11" onClick={() => setCopyMode("PREVIOUS_DAY")}>Copy Previous Day</Button>
          <Button variant={copyMode === "SAME_DAY_LAST_WEEK" ? "default" : "outline"} className="h-11" onClick={() => setCopyMode("SAME_DAY_LAST_WEEK")}>Copy Same Day Last Week</Button>
          <Button variant={copyMode === "DATE" ? "default" : "outline"} className="h-11" onClick={() => setCopyMode("DATE")}>Copy From Date</Button>
          <Button variant={copyMode === "SOURCE" ? "default" : "outline"} className="h-11" onClick={() => setCopyMode("SOURCE")}>Copy Existing Plan</Button>
        </div>
        {copyMode === "DATE" && <Field label="Historical Source Date"><Input type="date" value={copySourceDate} onChange={(e) => setCopySourceDate(e.target.value)} className="h-11" /></Field>}
        {copyMode === "SOURCE" && <Field label="Source Plan"><select className="control" value={copySourcePlanId} onChange={(e) => setCopySourcePlanId(e.target.value)}><option value="">Select existing plan</option>{plans.map((plan) => <option key={plan.id} value={plan.id}>{plan.planDate.slice(0, 10)} · {plan.planName}</option>)}</select></Field>}
        <div className="rounded-md border bg-muted/25 p-3 grid sm:grid-cols-2 lg:grid-cols-5 gap-2 text-sm">
          <Preview label="Source Plan" value={copySource?.planName ?? "No matching plan"} />
          <Preview label="Source Date" value={copySource ? new Date(copySource.planDate).toLocaleDateString() : "—"} />
          <Preview label="Number of Sets" value={copySource ? String(copySource.sets.length) : "—"} />
          <Preview label="New Plan Date" value={new Date(`${planDate}T12:00:00Z`).toLocaleDateString()} />
          <Preview label="New Generated Name" value={copyPreviewName || "—"} />
        </div>
        <Button className="w-full sm:w-auto h-11 bg-aqua hover:bg-aqua/90" disabled={!copySource || copying} onClick={copyPlan}><Copy /> {copying ? "Copying..." : "Confirm and Copy Plan"}</Button>
      </CardContent>
    </Card>
    <Card>
      <CardHeader><CardTitle className="text-base">{editingPlanId ? "Edit Training Plan" : "New Daily Plan"}</CardTitle></CardHeader>
      <CardContent className="space-y-4">
        <div className="grid sm:grid-cols-2 gap-3">
          <Field label="Plan Date"><Input type="date" value={planDate} onChange={(e) => setPlanDate(e.target.value)} className="h-11" /></Field>
          <Field label={`Plan Name${isPlanNameAutoGenerated ? " (automatic)" : ""}`}><Input value={planName} onChange={(e) => { const value = e.target.value; if (!value.trim()) { setPlanName(generatedPlanName); setPlanNameManuallyEdited(false); setIsPlanNameAutoGenerated(true); } else { setPlanName(value); setPlanNameManuallyEdited(true); setIsPlanNameAutoGenerated(false); } }} placeholder="Generated from date and styles" className="h-11" /></Field>
          <Field label="Training Period"><select className="control" value={period} onChange={(e) => setPeriod(e.target.value)}><option value="">No period</option><option value="Morning">Morning</option><option value="Afternoon">Afternoon</option><option value="Evening">Evening</option></select></Field>
          <Field label="Status"><select className="h-11 w-full rounded-md border bg-background px-3" value={status} onChange={(e) => setStatus(e.target.value as TrainingPlanStatus)}><option value="DRAFT">Draft</option><option value="ACTIVE">Active</option></select></Field>
          <Field label="Remarks"><Input value={remarks} onChange={(e) => setRemarks(e.target.value)} placeholder="Optional coach notes" className="h-11" /></Field>
        </div>
        <div className="space-y-3">
          {sets.map((set, index) => <Card key={set.key} className="border-muted"><CardContent className="p-3 sm:p-4 space-y-3">
            <div className="flex items-center justify-between"><Badge variant="secondary">Set {index + 1}</Badge><div className="flex gap-1"><Button size="icon" variant="ghost" onClick={() => move(index, -1)} disabled={index === 0} title="Move up"><ArrowUp /></Button><Button size="icon" variant="ghost" onClick={() => move(index, 1)} disabled={index === sets.length - 1} title="Move down"><ArrowDown /></Button><Button size="icon" variant="ghost" onClick={() => setSets((rows) => rows.filter((row) => row.key !== set.key))} disabled={sets.length === 1} title="Remove set"><Trash2 /></Button></div></div>
            <div className="grid grid-cols-2 lg:grid-cols-6 gap-3">
              <Field label="Distance"><Input type="number" min={1} value={set.distanceMeters} onChange={(e) => updateSet(set.key, { distanceMeters: Number(e.target.value) })} /></Field>
              <Field label="Repeats"><Input type="number" min={1} value={set.repeatCount} onChange={(e) => updateSet(set.key, { repeatCount: Number(e.target.value) })} /></Field>
              <Field label="Style" wide><select className="h-10 w-full rounded-md border bg-background px-2" value={set.swimmingStyleId} onChange={(e) => updateSet(set.key, { swimmingStyleId: e.target.value })}><option value="">Select style</option>{styles.map((style) => <option key={style.id} value={style.id}>{style.styleName}</option>)}</select></Field>
              <Field label="Target (sec)"><Input type="number" min={0} step="0.01" value={set.targetTimeSeconds} onChange={(e) => updateSet(set.key, { targetTimeSeconds: e.target.value })} /></Field>
              <Field label="Rest (sec)"><Input type="number" min={0} value={set.restIntervalSeconds} onChange={(e) => updateSet(set.key, { restIntervalSeconds: e.target.value })} /></Field>
            </div>
            <Field label="Notes"><Textarea rows={2} value={set.notes} onChange={(e) => updateSet(set.key, { notes: e.target.value })} /></Field>
            <p className="text-sm font-medium text-aqua">{set.distanceMeters}m x {set.repeatCount} {styles.find((style) => style.id === set.swimmingStyleId)?.styleName ?? "Style"}</p>
          </CardContent></Card>)}
        </div>
        <div className="flex flex-col sm:flex-row gap-2"><Button variant="outline" className="h-11" onClick={() => setSets((rows) => [...rows, { ...newSet(), swimmingStyleId: styles[0]?.id ?? "" }])}><Plus /> Add Set</Button>{editingPlanId && <Button variant="outline" className="h-11" onClick={resetForm}>Cancel Edit</Button>}<Button className="h-11 sm:ml-auto bg-aqua hover:bg-aqua/90" onClick={save} disabled={saving}><Save /> {saving ? "Saving..." : editingPlanId ? "Update Training Plan" : "Save Training Plan"}</Button></div>
      </CardContent>
    </Card>
    <div className="space-y-2"><h2 className="font-semibold">Recent Plans</h2>{plans.map((plan) => <Card key={plan.id}><CardContent className="p-3 sm:p-4 flex flex-col sm:flex-row sm:items-center gap-3"><div className="min-w-0 flex-1"><div className="flex flex-wrap items-center gap-2"><span className="font-semibold truncate">{plan.planName}</span><Badge>{plan.status}</Badge>{plan.copiedFromPlanId && <Badge variant="outline">Copied</Badge>}</div><p className="text-xs text-muted-foreground">{new Date(plan.planDate).toLocaleDateString()} · {plan.sets.length} sets · {plan._count?.runs ?? 0} runs</p><p className="text-sm mt-1 line-clamp-2">{plan.sets.map((set) => set.setLabel).join(" · ")}</p></div><div className="flex flex-col sm:flex-row gap-2">{["DRAFT", "ACTIVE"].includes(plan.status) && <Button variant="outline" className="h-10" onClick={() => openForEdit(plan)}><Pencil /> Edit</Button>}{plan.status !== "ACTIVE" && ["DRAFT", "ACTIVE"].includes(plan.status) && <Button variant="outline" className="h-10" onClick={() => activate(plan.id)}><PlayCircle /> Mark Active</Button>}</div></CardContent></Card>)}</div>
  </div>;
}

function Field({ label, children, wide }: { label: string; children: React.ReactNode; wide?: boolean }) {
  return <div className={`space-y-1 min-w-0 ${wide ? "col-span-2" : ""}`}><Label className="text-xs text-muted-foreground">{label}</Label>{children}</div>;
}

function Preview({ label, value }: { label: string; value: string }) {
  return <div className="min-w-0"><p className="text-[10px] uppercase text-muted-foreground">{label}</p><p className="font-medium break-words">{value}</p></div>;
}
